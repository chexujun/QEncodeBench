from qiskit import QuantumCircuit

def build_oracle(qc: QuantumCircuit, problem_qubits: list[int],
                 ancilla_qubits: list[int]) -> None:
    x0, x1, x2, x3 = problem_qubits
    a0, a1, a2, a3, a4, a5 = ancilla_qubits
    
    # Compute each clause into ancillas a1-a5, using a0 as temp
    
    # Clause 1: (x1 OR NOT x2 OR NOT x3) = NOT((NOT x1) AND x2 AND x3)
    qc.x(a0)
    qc.cx(x1, a0)
    qc.ccx(a0, x2, a2)
    qc.ccx(a2, x3, a1)
    qc.x(a1)
    qc.ccx(a2, x3, a1)
    qc.ccx(a0, x2, a2)
    qc.cx(x1, a0)
    qc.x(a0)
    
    # Clause 2: (NOT x0 OR NOT x2 OR x3) = NOT(x0 AND x2 AND (NOT x3))
    qc.cx(x0, a0)
    qc.ccx(a0, x2, a2)
    qc.x(a3)
    qc.cx(x3, a3)
    qc.ccx(a2, a3, a2)
    qc.x(a2)
    qc.ccx(a2, a3, a2)
    qc.cx(x3, a3)
    qc.x(a3)
    qc.ccx(a0, x2, a2)
    qc.cx(x0, a0)
    
    # Clause 3: (NOT x1 OR x2 OR x3) = NOT(x1 AND (NOT x2) AND (NOT x3))
    qc.cx(x1, a0)
    qc.x(a2)
    qc.cx(x2, a2)
    qc.ccx(a0, a2, a4)
    qc.x(a3)
    qc.cx(x3, a3)
    qc.ccx(a4, a3, a3)
    qc.x(a3)
    qc.ccx(a4, a3, a3)
    qc.cx(x3, a3)
    qc.x(a3)
    qc.ccx(a0, a2, a4)
    qc.cx(x2, a2)
    qc.x(a2)
    qc.cx(x1, a0)
    
    # Clause 4: (x0 OR x2 OR x3) = NOT((NOT x0) AND (NOT x2) AND (NOT x3))
    qc.x(a0)
    qc.cx(x0, a0)
    qc.x(a2)
    qc.cx(x2, a2)
    qc.ccx(a0, a2, a4)
    qc.x(a3)
    qc.cx(x3, a3)
    qc.ccx(a4, a3, a4)
    qc.x(a4)
    qc.ccx(a4, a3, a4)
    qc.cx(x3, a3)
    qc.x(a3)
    qc.ccx(a0, a2, a4)
    qc.cx(x2, a2)
    qc.x(a2)
    qc.cx(x0, a0)
    qc.x(a0)
    
    # Clause 5: (x0 OR NOT x2 OR NOT x3) = NOT((NOT x0) AND x2 AND x3)
    qc.x(a0)
    qc.cx(x0, a0)
    qc.ccx(a0, x2, a2)
    qc.ccx(a2, x3, a5)
    qc.x(a5)
    qc.ccx(a2, x3, a5)
    qc.ccx(a0, x2, a2)
    qc.cx(x0, a0)
    qc.x(a0)
    
    # AND all clauses and apply phase
    qc.ccx(a1, a2, a0)
    qc.ccx(a0, a3, a2)
    qc.ccx(a2, a4, a0)
    qc.ccx(a0, a5, a3)
    qc.z(a3)
    qc.ccx(a0, a5, a3)
    qc.ccx(a2, a4, a0)
    qc.ccx(a0, a3, a2)
    qc.ccx(a1, a2, a0)
