from qiskit import QuantumCircuit

def build_oracle(qc: QuantumCircuit, problem_qubits: list[int],
                 ancilla_qubits: list[int]) -> None:
    x0, x1, x2, x3 = problem_qubits
    a0, a1, a2, a3, a4, a5 = ancilla_qubits
    
    # Clause 1: (NOT x0 OR NOT x2 OR x3) = NOT(x0 AND x2 AND NOT x3)
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
    qc.x(a5)
    qc.cx(a5, a0)
    qc.x(a5)
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
    
    # Clause 2: (x0 OR x2 OR x3) = NOT(NOT x0 AND NOT x2 AND NOT x3)
    qc.x(x0)
    qc.x(x2)
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
    qc.x(x2)
    qc.x(x0)
    qc.x(a5)
    qc.cx(a5, a1)
    qc.x(a5)
    qc.x(x0)
    qc.x(x2)
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
    qc.x(x2)
    qc.x(x0)
    
    # Clause 3: (x0 OR NOT x2 OR x3) = NOT(NOT x0 AND x2 AND NOT x3)
    qc.x(x0)
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
    qc.x(x0)
    qc.x(a5)
    qc.cx(a5, a2)
    qc.x(a5)
    qc.x(x0)
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
    qc.x(x0)
    
    # Clause 4: (x0 OR NOT x1 OR NOT x2) = NOT(NOT x0 AND x1 AND x2)
    qc.x(x0)
    qc.mcx([x0, x1, x2], a5)
    qc.x(x0)
    qc.x(a5)
    qc.cx(a5, a3)
    qc.x(a5)
    qc.x(x0)
    qc.mcx([x0, x1, x2], a5)
    qc.x(x0)
    
    # Clause 5: (NOT x0 OR NOT x2 OR NOT x3) = NOT(x0 AND x2 AND x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(a5)
    qc.cx(a5, a4)
    qc.x(a5)
    qc.mcx([x0, x2, x3], a5)
    
    # Compute AND of all clause satisfactions and apply phase
    qc.mcx([a0, a1, a2, a3, a4], a5)
    qc.z(a5)
    qc.mcx([a0, a1, a2, a3, a4], a5)
    
    # Uncompute all clauses in reverse order
    qc.mcx([x0, x2, x3], a5)
    qc.x(a5)
    qc.cx(a5, a4)
    qc.x(a5)
    qc.mcx([x0, x2, x3], a5)
    
    qc.x(x0)
    qc.mcx([x0, x1, x2], a5)
    qc.x(x0)
    qc.x(a5)
    qc.cx(a5, a3)
    qc.x(a5)
    qc.x(x0)
    qc.mcx([x0, x1, x2], a5)
    qc.x(x0)
    
    qc.x(x0)
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
    qc.x(x0)
    qc.x(a5)
    qc.cx(a5, a2)
    qc.x(a5)
    qc.x(x0)
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
    qc.x(x0)
    
    qc.x(x0)
    qc.x(x2)
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
    qc.x(x2)
    qc.x(x0)
    qc.x(a5)
    qc.cx(a5, a1)
    qc.x(a5)
    qc.x(x0)
    qc.x(x2)
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
    qc.x(x2)
    qc.x(x0)
    
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
    qc.x(a5)
    qc.cx(a5, a0)
    qc.x(a5)
    qc.x(x3)
    qc.mcx([x0, x2, x3], a5)
    qc.x(x3)
