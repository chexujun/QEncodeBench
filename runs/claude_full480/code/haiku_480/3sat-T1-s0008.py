def build_oracle(qc, problem_qubits, ancilla_qubits):
    x = problem_qubits
    a = ancilla_qubits
    
    # Clause 0: (NOT x0 OR x1 OR NOT x2)
    qc.x(x[1])
    qc.ccx(x[0], x[1], a[0])
    qc.ccx(a[0], x[2], a[5])
    qc.cx(a[5], a[0])
    qc.cx(a[0], a[5])
    qc.cx(a[5], a[0])
    qc.ccx(x[0], x[1], a[5])
    qc.x(x[1])
    qc.x(a[0])
    
    # Clause 1: (NOT x1 OR x2 OR NOT x3)
    qc.x(x[2])
    qc.ccx(x[1], x[2], a[1])
    qc.ccx(a[1], x[3], a[5])
    qc.cx(a[5], a[1])
    qc.cx(a[1], a[5])
    qc.cx(a[5], a[1])
    qc.ccx(x[1], x[2], a[5])
    qc.x(x[2])
    qc.x(a[1])
    
    # Clause 2: (NOT x1 OR NOT x2 OR NOT x3)
    qc.ccx(x[1], x[2], a[2])
    qc.ccx(a[2], x[3], a[5])
    qc.cx(a[5], a[2])
    qc.cx(a[2], a[5])
    qc.cx(a[5], a[2])
    qc.ccx(x[1], x[2], a[5])
    qc.x(a[2])
    
    # Clause 3: (x1 OR x2 OR NOT x3)
    qc.x(x[1])
    qc.x(x[2])
    qc.ccx(x[1], x[2], a[3])
    qc.ccx(a[3], x[3], a[5])
    qc.cx(a[5], a[3])
    qc.cx(a[3], a[5])
    qc.cx(a[5], a[3])
    qc.ccx(x[1], x[2], a[5])
    qc.x(x[2])
    qc.x(x[1])
    qc.x(a[3])
    
    # Clause 4: (x0 OR NOT x2 OR NOT x3)
    qc.x(x[0])
    qc.ccx(x[0], x[2], a[4])
    qc.ccx(a[4], x[3], a[5])
    qc.cx(a[5], a[4])
    qc.cx(a[4], a[5])
    qc.cx(a[5], a[4])
    qc.ccx(x[0], x[2], a[5])
    qc.x(x[0])
    qc.x(a[4])
    
    # AND all clauses into a[5]
    qc.mcx([a[0], a[1], a[2], a[3], a[4]], a[5])
    
    # Apply phase flip
    qc.z(a[5])
    
    # Uncompute AND
    qc.mcx([a[0], a[1], a[2], a[3], a[4]], a[5])
    
    # Uncompute clauses (reverse order)
    qc.x(a[4])
    qc.x(x[0])
    qc.ccx(x[0], x[2], a[5])
    qc.cx(a[5], a[4])
    qc.cx(a[4], a[5])
    qc.cx(a[5], a[4])
    qc.ccx(a[4], x[3], a[5])
    qc.ccx(x[0], x[2], a[4])
    qc.x(x[0])
    
    qc.x(a[3])
    qc.x(x[1])
    qc.x(x[2])
    qc.ccx(x[1], x[2], a[5])
    qc.cx(a[5], a[3])
    qc.cx(a[3], a[5])
    qc.cx(a[5], a[3])
    qc.ccx(a[3], x[3], a[5])
    qc.ccx(x[1], x[2], a[3])
    qc.x(x[2])
    qc.x(x[1])
    
    qc.x(a[2])
    qc.ccx(x[1], x[2], a[5])
    qc.cx(a[5], a[2])
    qc.cx(a[2], a[5])
    qc.cx(a[5], a[2])
    qc.ccx(a[2], x[3], a[5])
    qc.ccx(x[1], x[2], a[2])
    
    qc.x(a[1])
    qc.x(x[2])
    qc.ccx(x[1], x[2], a[5])
    qc.cx(a[5], a[1])
    qc.cx(a[1], a[5])
    qc.cx(a[5], a[1])
    qc.ccx(a[1], x[3], a[5])
    qc.ccx(x[1], x[2], a[1])
    qc.x(x[2])
    
    qc.x(a[0])
    qc.x(x[1])
    qc.ccx(x[0], x[1], a[5])
    qc.cx(a[5], a[0])
    qc.cx(a[0], a[5])
    qc.cx(a[5], a[0])
    qc.ccx(a[0], x[2], a[5])
    qc.ccx(x[0], x[1], a[0])
    qc.x(x[1])
