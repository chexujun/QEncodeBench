from qiskit import QuantumCircuit

def build_oracle(qc: QuantumCircuit, problem_qubits: list[int],
                 ancilla_qubits: list[int]) -> None:
    x0, x1, x2, x3 = problem_qubits
    main, a1, a2, a3, a4, a5 = ancilla_qubits
    
    qc.x(main)
    
    # Clause 1: false iff x0 AND x2 AND x3
    qc.ccx(x0, x2, a2)
    qc.ccx(a2, x3, a1)
    qc.cx(a1, main)
    qc.ccx(a2, x3, a1)
    qc.ccx(x0, x2, a2)
    
    # Clause 2: false iff NOT x0 AND NOT x2 AND NOT x3
    qc.x(a1)
    qc.cx(x0, a1)
    qc.x(a2)
    qc.cx(x2, a2)
    qc.x(a3)
    qc.cx(x3, a3)
    qc.ccx(a1, a2, a4)
    qc.ccx(a4, a3, a5)
    qc.cx(a5, main)
    qc.ccx(a4, a3, a5)
    qc.ccx(a1, a2, a4)
    qc.cx(x3, a3)
    qc.x(a3)
    qc.cx(x2, a2)
    qc.x(a2)
    qc.cx(x0, a1)
    qc.x(a1)
    
    # Clause 3: false iff NOT x0 AND NOT x2 AND x3
    qc.x(a1)
    qc.cx(x0, a1)
    qc.x(a2)
    qc.cx(x2, a2)
    qc.ccx(a1, a2, a4)
    qc.ccx(a4, x3, a5)
    qc.cx(a5, main)
    qc.ccx(a4, x3, a5)
    qc.ccx(a1, a2, a4)
    qc.cx(x2, a2)
    qc.x(a2)
    qc.cx(x0, a1)
    qc.x(a1)
    
    # Clause 4: false iff NOT x1 AND NOT x2 AND x3
    qc.x(a1)
    qc.cx(x1, a1)
    qc.x(a2)
    qc.cx(x2, a2)
    qc.ccx(a1, a2, a4)
    qc.ccx(a4, x3, a5)
    qc.cx(a5, main)
    qc.ccx(a4, x3, a5)
    qc.ccx(a1, a2, a4)
    qc.cx(x2, a2)
    qc.x(a2)
    qc.cx(x1, a1)
    qc.x(a1)
    
    # Clause 5: false iff NOT x0 AND NOT x1 AND x2
    qc.x(a1)
    qc.cx(x0, a1)
    qc.x(a2)
    qc.cx(x1, a2)
    qc.ccx(a1, a2, a4)
    qc.ccx(a4, x2, a5)
    qc.cx(a5, main)
    qc.ccx(a4, x2, a5)
    qc.ccx(a1, a2, a4)
    qc.cx(x1, a2)
    qc.x(a2)
    qc.cx(x0, a1)
    qc.x(a1)
    
    qc.z(main)
    
    # Uncompute Clause 5
    qc.x(a1)
    qc.cx(x0, a1)
    qc.x(a2)
    qc.cx(x1, a2)
    qc.ccx(a1, a2, a4)
    qc.ccx(a4, x2, a5)
    qc.cx(a5, main)
    qc.ccx(a4, x2, a5)
    qc.ccx(a1, a2, a4)
    qc.cx(x1, a2)
    qc.x(a2)
    qc.cx(x0, a1)
    qc.x(a1)
    
    # Uncompute Clause 4
    qc.x(a1)
    qc.cx(x1, a1)
    qc.x(a2)
    qc.cx(x2, a2)
    qc.ccx(a1, a2, a4)
    qc.ccx(a4, x3, a5)
    qc.cx(a5, main)
    qc.ccx(a4, x3, a5)
    qc.ccx(a1, a2, a4)
    qc.cx(x2, a2)
    qc.x(a2)
    qc.cx(x1, a1)
    qc.x(a1)
    
    # Uncompute Clause 3
    qc.x(a1)
    qc.cx(x0, a1)
    qc.x(a2)
    qc.cx(x2, a2)
    qc.ccx(a1, a2, a4)
    qc.ccx(a4, x3, a5)
    qc.cx(a5, main)
    qc.ccx(a4, x3, a5)
    qc.ccx(a1, a2, a4)
    qc.cx(x2, a2)
    qc.x(a2)
    qc.cx(x0, a1)
    qc.x(a1)
    
    # Uncompute Clause 2
    qc.x(a1)
    qc.cx(x0, a1)
    qc.x(a2)
    qc.cx(x2, a2)
    qc.x(a3)
    qc.cx(x3, a3)
    qc.ccx(a1, a2, a4)
    qc.ccx(a4, a3, a5)
    qc.cx(a5, main)
    qc.ccx(a4, a3, a5)
    qc.ccx(a1, a2, a4)
    qc.cx(x3, a3)
    qc.x(a3)
    qc.cx(x2, a2)
    qc.x(a2)
    qc.cx(x0, a1)
    qc.x(a1)
    
    # Uncompute Clause 1
    qc.ccx(x0, x2, a2)
    qc.ccx(a2, x3, a1)
    qc.cx(a1, main)
    qc.ccx(a2, x3, a1)
    qc.ccx(x0, x2, a2)
    
    qc.x(main)
