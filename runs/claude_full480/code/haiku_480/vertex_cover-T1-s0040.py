from qiskit import QuantumCircuit

def build_oracle(qc: QuantumCircuit, problem_qubits: list[int],
                 ancilla_qubits: list[int]) -> None:
    x = problem_qubits
    a = ancilla_qubits
    
    # Oracle for vertex covers of size ≤ 2 in graph with edges (0,1), (1,3), (2,3)
    # Valid solutions: {0,3}, {1,2}, {1,3}
    # Conditions:
    #   Term1: x[0]=1, x[1]=0, x[2]=0, x[3]=1 → x[0] ∧ ¬x[1] ∧ ¬x[2] ∧ x[3]
    #   Term2: x[0]=0, x[1]=1, x[2]=1, x[3]=0 → ¬x[0] ∧ x[1] ∧ x[2] ∧ ¬x[3]
    #   Term3: x[0]=0, x[1]=1, x[2]=0, x[3]=1 → ¬x[0] ∧ x[1] ∧ ¬x[2] ∧ x[3]
    # Result: Term1 ⊕ Term2 ⊕ Term3 (terms are mutually exclusive)
    
    # Compute and accumulate each term via XOR into a[5]
    
    # Term 1: x[0] ∧ ¬x[1] ∧ ¬x[2] ∧ x[3]
    qc.x(x[1])
    qc.cx(x[1], a[0])
    qc.x(x[1])
    qc.x(x[2])
    qc.cx(x[2], a[1])
    qc.x(x[2])
    qc.ccx(x[0], a[0], a[2])
    qc.ccx(a[1], a[2], a[3])
    qc.ccx(x[3], a[3], a[4])
    qc.cx(a[4], a[5])
    qc.ccx(x[3], a[3], a[4])
    qc.ccx(a[1], a[2], a[3])
    qc.ccx(x[0], a[0], a[2])
    qc.x(x[2])
    qc.cx(x[2], a[1])
    qc.x(x[2])
    qc.x(x[1])
    qc.cx(x[1], a[0])
    qc.x(x[1])
    
    # Term 2: ¬x[0] ∧ x[1] ∧ x[2] ∧ ¬x[3]
    qc.x(x[0])
    qc.cx(x[0], a[0])
    qc.x(x[0])
    qc.x(x[3])
    qc.cx(x[3], a[1])
    qc.x(x[3])
    qc.ccx(a[0], x[1], a[2])
    qc.ccx(x[2], a[2], a[3])
    qc.ccx(a[1], a[3], a[4])
    qc.cx(a[4], a[5])
    qc.ccx(a[1], a[3], a[4])
    qc.ccx(x[2], a[2], a[3])
    qc.ccx(a[0], x[1], a[2])
    qc.x(x[3])
    qc.cx(x[3], a[1])
    qc.x(x[3])
    qc.x(x[0])
    qc.cx(x[0], a[0])
    qc.x(x[0])
    
    # Term 3: ¬x[0] ∧ x[1] ∧ ¬x[2] ∧ x[3]
    qc.x(x[0])
    qc.cx(x[0], a[0])
    qc.x(x[0])
    qc.x(x[2])
    qc.cx(x[2], a[1])
    qc.x(x[2])
    qc.ccx(a[0], x[1], a[2])
    qc.ccx(a[1], a[2], a[3])
    qc.ccx(x[3], a[3], a[4])
    qc.cx(a[4], a[5])
    qc.ccx(x[3], a[3], a[4])
    qc.ccx(a[1], a[2], a[3])
    qc.ccx(a[0], x[1], a[2])
    qc.x(x[2])
    qc.cx(x[2], a[1])
    qc.x(x[2])
    qc.x(x[0])
    qc.cx(x[0], a[0])
    qc.x(x[0])
    
    # Apply phase
    qc.z(a[5])
    
    # Uncompute (mirror of compute)
    qc.x(x[0])
    qc.cx(x[0], a[0])
    qc.x(x[0])
    qc.x(x[2])
    qc.cx(x[2], a[1])
    qc.x(x[2])
    qc.ccx(a[0], x[1], a[2])
    qc.ccx(a[1], a[2], a[3])
    qc.ccx(x[3], a[3], a[4])
    qc.cx(a[4], a[5])
    qc.ccx(x[3], a[3], a[4])
    qc.ccx(a[1], a[2], a[3])
    qc.ccx(a[0], x[1], a[2])
    qc.x(x[2])
    qc.cx(x[2], a[1])
    qc.x(x[2])
    qc.x(x[0])
    qc.cx(x[0], a[0])
    qc.x(x[0])
    
    qc.x(x[0])
    qc.cx(x[0], a[0])
    qc.x(x[0])
    qc.x(x[3])
    qc.cx(x[3], a[1])
    qc.x(x[3])
    qc.ccx(a[0], x[1], a[2])
    qc.ccx(x[2], a[2], a[3])
    qc.ccx(a[1], a[3], a[4])
    qc.cx(a[4], a[5])
    qc.ccx(a[1], a[3], a[4])
    qc.ccx(x[2], a[2], a[3])
    qc.ccx(a[0], x[1], a[2])
    qc.x(x[3])
    qc.cx(x[3], a[1])
    qc.x(x[3])
    qc.x(x[0])
    qc.cx(x[0], a[0])
    qc.x(x[0])
    
    qc.x(x[1])
    qc.cx(x[1], a[0])
    qc.x(x[1])
    qc.x(x[2])
    qc.cx(x[2], a[1])
    qc.x(x[2])
    qc.ccx(x[0], a[0], a[2])
    qc.ccx(a[1], a[2], a[3])
    qc.ccx(x[3], a[3], a[4])
    qc.cx(a[4], a[5])
    qc.ccx(x[3], a[3], a[4])
    qc.ccx(a[1], a[2], a[3])
    qc.ccx(x[0], a[0], a[2])
    qc.x(x[2])
    qc.cx(x[2], a[1])
    qc.x(x[2])
    qc.x(x[1])
    qc.cx(x[1], a[0])
    qc.x(x[1])
